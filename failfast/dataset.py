"""Dataset builder for FailFast training data.

Pairs historical commits with their test outcomes to produce labeled feature
matrices suitable for ML training.

Label definition
----------------
A test is labeled ``1`` (positive) if its outcome was ``'failed'`` or
``'error'`` on that commit, and ``0`` otherwise.

Train/test split
----------------
Splits are **always** time-based: rows are sorted by ``commit_timestamp`` and
the first ``train_ratio`` fraction is the training set.  Random splits are
explicitly excluded because they would cause data leakage across commits.

Output format
-------------
Datasets are saved to the ``data/`` directory (git-ignored) as Parquet files
when PyArrow is available, or as CSV files otherwise.  The chosen format is
noted in the file name.

Synthetic-data note
-------------------
Datasets generated by :mod:`failfast.simulate` are tagged with
``synthetic=True`` in the manifest and carry the column ``is_synthetic=1`` in
the saved file.  This column must never be dropped before training so that
models can be conditioned on or filtered by data origin.
"""

from __future__ import annotations

import json
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    import pandas as pd


# Outcomes counted as label = 1 (test failed on this commit)
_FAILURE_OUTCOMES: frozenset[str] = frozenset({"failed", "error"})


@dataclass
class DatasetManifest:
    """Metadata written alongside each saved dataset.

    Attributes:
        created_at: Unix timestamp when the dataset was built.
        num_rows: Total number of rows.
        num_positives: Rows with label == 1.
        feature_columns: List of feature column names (in order).
        synthetic: Whether the data was produced by the simulator.
        split_ratio: Fraction used for training in time splits.
    """

    created_at: float = field(default_factory=time.time)
    num_rows: int = 0
    num_positives: int = 0
    feature_columns: list[str] = field(default_factory=list)
    synthetic: bool = False
    split_ratio: float = 0.8


def build_labeled_dataset(
    feature_rows: pd.DataFrame,
    outcome_map: dict[str, str],
    *,
    is_synthetic: bool = False,
) -> pd.DataFrame:
    """Attach labels to a feature DataFrame.

    Args:
        feature_rows: DataFrame indexed by ``node_id`` as produced by
            :func:`failfast.features.builder.build_features`.
        outcome_map: Mapping from ``node_id`` to outcome string (e.g.
            ``'passed'``, ``'failed'``).
        is_synthetic: If ``True``, adds an ``is_synthetic`` column set to 1
            for every row.  See module docstring for details.

    Returns:
        A copy of *feature_rows* with a ``label`` column (int, 0 or 1) and
        optionally an ``is_synthetic`` column.
    """

    df = feature_rows.copy()
    df["label"] = df.index.map(
        lambda nid: 1 if outcome_map.get(nid) in _FAILURE_OUTCOMES else 0
    )
    if is_synthetic:
        df["is_synthetic"] = 1
    return df


def time_split(
    dataset: pd.DataFrame,
    *,
    timestamp_col: str = "commit_timestamp",
    train_ratio: float = 0.8,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Split *dataset* into train and test sets by time order.

    Rows are sorted ascending by *timestamp_col*.  The first ``train_ratio``
    fraction forms the training set; the remainder is the test set.  No
    shuffling is performed.

    Args:
        dataset: DataFrame that must contain *timestamp_col*.
        timestamp_col: Column name holding the commit Unix timestamp.
        train_ratio: Fraction of rows for training (0 < ratio < 1).

    Returns:
        ``(train_df, test_df)`` tuple.

    Raises:
        ValueError: If *train_ratio* is not strictly between 0 and 1.
        KeyError: If *timestamp_col* is not in the dataset columns.
    """
    if not (0.0 < train_ratio < 1.0):
        raise ValueError(f"train_ratio must be in (0, 1), got {train_ratio}")
    if timestamp_col not in dataset.columns:
        raise KeyError(f"Column '{timestamp_col}' not found in dataset")

    sorted_df = dataset.sort_values(timestamp_col).reset_index(drop=True)
    cutoff = int(len(sorted_df) * train_ratio)
    return sorted_df.iloc[:cutoff].copy(), sorted_df.iloc[cutoff:].copy()


def save_dataset(
    dataset: pd.DataFrame,
    output_dir: Path,
    name: str,
    *,
    is_synthetic: bool = False,
) -> Path:
    """Persist *dataset* to *output_dir* and write a manifest JSON alongside it.

    Prefers Parquet (via PyArrow) and falls back to CSV when PyArrow is not
    installed.

    Args:
        dataset: The labeled DataFrame to save.
        output_dir: Directory path (created if it does not exist).
        name: Base name for the output file (without extension).
        is_synthetic: Passed to :class:`DatasetManifest`.

    Returns:
        Path to the saved data file.
    """
    output_dir.mkdir(parents=True, exist_ok=True)

    # Try Parquet first
    try:
        import pyarrow  # noqa: F401

        out_path = output_dir / f"{name}.parquet"
        dataset.to_parquet(out_path, index=True)
        fmt = "parquet"
    except ImportError:
        out_path = output_dir / f"{name}.csv"
        dataset.to_csv(out_path, index=True)
        fmt = "csv"

    feature_cols = [c for c in dataset.columns if c not in {"label", "is_synthetic"}]

    manifest = DatasetManifest(
        num_rows=len(dataset),
        num_positives=(
            int((dataset["label"] == 1).sum()) if "label" in dataset.columns else 0
        ),
        feature_columns=feature_cols,
        synthetic=is_synthetic,
    )

    manifest_path = output_dir / f"{name}_manifest.json"
    manifest_path.write_text(
        json.dumps(
            {
                "format": fmt,
                "created_at": manifest.created_at,
                "num_rows": manifest.num_rows,
                "num_positives": manifest.num_positives,
                "feature_columns": manifest.feature_columns,
                "synthetic": manifest.synthetic,
            },
            indent=2,
        ),
        encoding="utf-8",
    )

    return out_path


def load_dataset(path: Path) -> pd.DataFrame:
    """Load a dataset saved by :func:`save_dataset`.

    Args:
        path: Path to the Parquet or CSV file.

    Returns:
        The loaded :class:`pandas.DataFrame`.

    Raises:
        ValueError: If the file extension is not recognised.
    """
    import pandas as pd

    suffix = path.suffix.lower()
    if suffix == ".parquet":
        return pd.read_parquet(path)
    elif suffix == ".csv":
        return pd.read_csv(path, index_col=0)
    else:
        raise ValueError(f"Unsupported dataset format: {suffix}")
